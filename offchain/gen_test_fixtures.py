"""Generate Rust fixtures for scam_detector tests from offchain/weights.json.

Output: anchor/programs/scam_detector/tests/fixtures.rs (auto-generated, DO NOT EDIT)

Chạy: offchain\\.venv\\Scripts\\python.exe -X utf8 offchain/gen_test_fixtures.py
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from featurize import featurize  # noqa: E402

# 1 mau scam + 1 mau binh thuong (khop mau da train)
SCAM_TEXT = "Cung cap OTP 778899 de xac minh tai khoan http://nhan-qua.xyz"
NORMAL_TEXT = "Hom nay troi dep qua ban oi"


def rust_arr(vals, ty):
    # Type is declared on the const (e.g. `[i8; 4096]`); a trailing `as ty`
    # would be an invalid non-primitive cast in Rust, so we omit it.
    return "[" + ", ".join(str(v) for v in vals) + "]"


def main():
    w = json.loads((HERE / "weights.json").read_text(encoding="utf-8"))
    scam_f = featurize(SCAM_TEXT).tolist()
    norm_f = featurize(NORMAL_TEXT).tolist()

    out = f"""// Auto-generated by offchain/gen_test_fixtures.py. DO NOT EDIT by hand.
#![allow(clippy::all)]

pub const W1: [i8; 4096] = {rust_arr(w["w1"], "i8")};
pub const B1: [i32; 16] = {rust_arr(w["b1"], "i32")};
pub const W2: [i8; 16] = {rust_arr(w["w2"], "i8")};
pub const B2: i32 = {w["b2"]};
pub const SCALE_W1: i32 = {w["scale_w1"]};
pub const SCALE_W2: i32 = {w["scale_w2"]};
pub const SCALE_B1: i32 = {w["scale_b1"]};
pub const SCALE_B2: i32 = {w["scale_b2"]};
pub const SHIFT: u8 = {w["shift"]};
pub const K_SIGMOID: i32 = {w["k_sigmoid"]};

pub const SCAM_TEXT: &str = {json.dumps(SCAM_TEXT, ensure_ascii=False)};
pub const NORMAL_TEXT: &str = {json.dumps(NORMAL_TEXT, ensure_ascii=False)};
pub const SCAM_FEATURES: [i8; 256] = {rust_arr(scam_f, "i8")};
pub const NORMAL_FEATURES: [i8; 256] = {rust_arr(norm_f, "i8")};
"""
    dest = HERE.parent / "anchor" / "programs" / "scam_detector" / "tests" / "fixtures.rs"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(out, encoding="utf-8")
    print(f"wrote {dest} ({dest.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
